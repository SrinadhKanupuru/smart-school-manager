  // Indian Rupee currency formatter helper
  static String formatInr(num amount) {
    // Simple Indian number formatting: e.g. 1876200 -> ₹18,76,200
    String str = amount.toInt().toString();
    if (str.length <= 3) return '₹$str';
    String lastThree = str.substring(str.length - 3);
    String remaining = str.substring(0, str.length - 3);
    RegExp reg = RegExp(r'(\d+?)(?=(\d{2})+$)');
    String formattedRemaining = remaining.replaceAllMapped(reg, (Match m) => '${m[1]},');
    return '₹$formattedRemaining,$lastThree';
  }

